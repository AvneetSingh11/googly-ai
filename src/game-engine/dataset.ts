export function getPlayerById(id: string): IPLPlayer | undefined {
  return IPL_PLAYERS.find((p) => p.id === id);
}

export function getPlayerByName(name: string): IPLPlayer | undefined {
  const lower = name.toLowerCase();
  return IPL_PLAYERS.find(
    (p) =>
      p.name.toLowerCase() === lower ||
      p.fullName.toLowerCase() === lower
  );
}

export function getTeamByShortName(shortName: string): IPLTeam | undefined {
  return IPL_TEAMS.find(
    (t) => t.shortName.toLowerCase() === shortName.toLowerCase()
  );
}

export function getTeamByName(name: string): IPLTeam | undefined {
  const lower = name.toLowerCase();
  return IPL_TEAMS.find(
    (t) =>
      t.name.toLowerCase() === lower ||
      t.shortName.toLowerCase() === lower
  );
}

export function getMatchById(id: string): IPLMatch | undefined {
  return IPL_MATCHES.find((m) => m.id === id);
}

export function searchPlayers(query: string): IPLPlayer[] {
  const lower = query.toLowerCase();
  return IPL_PLAYERS.filter(
    (p) =>
      p.name.toLowerCase().includes(lower) ||
      p.fullName.toLowerCase().includes(lower) ||
      p.nationality.toLowerCase().includes(lower) ||
      p.teams.some((t) => t.toLowerCase().includes(lower)) ||
      p.iconicTraits.some((t) => t.toLowerCase().includes(lower))
  );
}

export function searchTeams(query: string): IPLTeam[] {
  const lower = query.toLowerCase();
  return IPL_TEAMS.filter(
    (t) =>
      t.name.toLowerCase().includes(lower) ||
      t.shortName.toLowerCase().includes(lower) ||
      t.homeCity.toLowerCase().includes(lower)
  );
}

export function searchMatches(query: string): IPLMatch[] {
  const lower = query.toLowerCase();
  return IPL_MATCHES.filter(
    (m) =>
      m.title.toLowerCase().includes(lower) ||
      m.description.toLowerCase().includes(lower) ||
      m.team1.toLowerCase().includes(lower) ||
      m.team2.toLowerCase().includes(lower) ||
      m.playerOfTheMatch.toLowerCase().includes(lower)
  );
}

